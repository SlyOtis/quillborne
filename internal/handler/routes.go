package handler

import (
	"net/http"

	"github.com/labstack/echo/v4"
)

func PutRoutes(api *echo.Group, userAuth echo.MiddlewareFunc) {
	profile := api.Group("/profile", userAuth)
	profile.GET("", GetProfile)
	profile.POST("", PostProfile)
	profile.PUT("", PutProfile)
	profile.GET("/stream", GetProfileStream)
	profile.GET("/list", GetProfiles)
	profile.GET("/details", GetProfileDetails)
	profile.PUT("/details", PutProfileDetails)
	profile.POST("/friend", PostProfileFriend)
	profile.DELETE("/friend/:user_id", DeleteProfileFriend)
	profile.GET("/:user_id", GetProfileUser)

	character := api.Group("/character", userAuth)
	character.GET("", GetCharacters)
	character.POST("", PostCharacter)
	character.GET("/:id", GetCharacter)
	character.PUT("/:id", PutCharacter)
	character.DELETE("/:id", DeleteCharacter)
	character.PUT("/:id/played", PutCharacterPlayed)
	character.GET("/:id/sources", GetCharacterSources)
	character.PUT("/:id/sources", PutCharacterSources)
	character.GET("/:id/stream", GetCharacterStream)

	vehicle := api.Group("/vehicle", userAuth)
	vehicle.GET("", GetVehicles)
	vehicle.POST("", PostVehicle)
	vehicle.GET("/:id", GetVehicle)
	vehicle.PUT("/:id", PutVehicle)
	vehicle.DELETE("/:id", DeleteVehicle)
	vehicle.GET("/:id/stream", GetVehicleStream)

	campaign := api.Group("/campaign", userAuth)
	campaign.GET("", GetCampaigns)
	campaign.POST("", PostCampaign)
	campaign.GET("/:id", GetCampaign)
	campaign.PUT("/:id", PutCampaign)
	campaign.DELETE("/:id", DeleteCampaign)
	campaign.POST("/:id/player", PostCampaignPlayer)
	campaign.DELETE("/:id/player/:user_id", DeleteCampaignPlayer)
	campaign.GET("/:id/character", GetCampaignCharacters)
	campaign.POST("/:id/character/:character_id", PostCampaignCharacter)
	campaign.DELETE("/:id/character/:character_id", DeleteCampaignCharacter)
	campaign.GET("/:id/stream", GetCampaignStream)
	campaign.GET("/:id/map", GetMaps)
	campaign.POST("/:id/map", PostMap)
	campaign.PUT("/:id/map/:map_id", PutMap)
	campaign.DELETE("/:id/map/:map_id", DeleteMap)
	campaign.GET("/:id/encounter", GetEncounters)
	campaign.POST("/:id/encounter", PostEncounter)
	campaign.PUT("/:id/encounter/:encounter_id", PutEncounter)
	campaign.DELETE("/:id/encounter/:encounter_id", DeleteEncounter)
	campaign.GET("/:id/song", GetSongs)
	campaign.POST("/:id/song", PostSong)
	campaign.PUT("/:id/song/:song_id", PutSong)
	campaign.DELETE("/:id/song/:song_id", DeleteSong)
	campaign.GET("/:id/chat", GetChatEntries)
	campaign.POST("/:id/chat", PostChatEntry)
	campaign.PUT("/:id/chat/:entry_id", PutChatEntry)
	campaign.DELETE("/:id/chat/:entry_id", DeleteChatEntry)

	resource := api.Group("/resource", userAuth)
	resource.GET("", GetResources)
	resource.POST("", PostResource)
	resource.GET("/:id", GetResource)
	resource.PUT("/:id", PutResource)
	resource.DELETE("/:id", DeleteResource)
	resource.GET("/:id/stream", GetResourceStream)
	resource.GET("/:id/update", GetResourceUpdates)
	resource.POST("/:id/update", PostResourceUpdate)
	resource.PUT("/:id/update", PutResourceUpdates)
	resource.DELETE("/:id/update", DeleteResourceUpdates)

	asset := api.Group("/asset", userAuth)
	asset.GET("", GetAssets)
	asset.POST("", PostAsset)
	asset.GET("/object", GetObjectAssets)
	asset.GET("/:id", GetAsset)
	asset.POST("/:id", PostAssetUpload)
	asset.PUT("/:id", PutAsset)
	asset.DELETE("/:id", DeleteAsset)
	asset.GET("/:id/data", GetAssetData)
	asset.HEAD("/:id/data", GetAssetData)
	asset.POST("/:id/object", PostObjectAsset)
	asset.PUT("/:id/object", PutObjectAsset)
	asset.DELETE("/:id/object/:object_id", DeleteObjectAsset)

	file := api.Group("/file", userAuth)
	file.GET("", GetFiles)
	file.GET("/:id", GetFile)
	file.POST("/move", PostAssetMove)

	tag := api.Group("/tag", userAuth)
	tag.GET("", GetTags)
	tag.POST("", PostTag)
	tag.GET("/:id", GetTag)
	tag.PUT("/:id", PutTag)
	tag.DELETE("/:id", DeleteTag)
	tag.POST("/:id/object", PostTagObject)
	tag.DELETE("/:id/object", DeleteTagObject)

	ai := api.Group("/ai", userAuth)
	ai.Match([]string{http.MethodGet, http.MethodPost}, "/*", PostAI)

	catalog := api.Group("/catalog", userAuth)
	catalog.GET("/:kind", GetCatalogEntries)
	catalog.GET("/:kind/:slug", GetCatalogEntry)
	catalog.PUT("/:kind/:slug", PutCatalogEntry)

	claim := api.Group("/claim", userAuth)
	claim.POST("", PostClaim)
	claim.GET("/:id", GetClaim)
	claim.POST("/:id/user", PostClaimUser)
	claim.DELETE("/:id/user/:user_id", DeleteClaimUser)
	claim.POST("/:id/object", PostClaimObject)
	claim.DELETE("/:id/object/:object_id", DeleteClaimObject)
	api.GET("/:type/:id/claim", GetObjectClaims, userAuth)
}
